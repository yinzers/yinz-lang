use std::collections::HashSet;
use std::fmt::Write as FmtWrite;
use std::path::PathBuf;

fn main() {
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let toml_path = manifest_dir.join("../../registry/features.toml");

    // Only re-run when the TOML changes — touching any other file must not re-run this script.
    println!("cargo:rerun-if-changed={}", toml_path.display());

    let src = std::fs::read_to_string(&toml_path)
        .unwrap_or_else(|e| panic!("registry/features.toml: cannot read: {e}"));

    // Strip UTF-8 BOM if present — relevant for Windows contributors.
    let src = src.strip_prefix('\u{FEFF}').unwrap_or(&src);

    let doc: toml::Value = toml::from_str(src)
        .unwrap_or_else(|e| panic!("registry/features.toml: TOML parse error: {e}"));

    let table = doc
        .as_table()
        .expect("registry/features.toml: top level must be a TOML table");

    let mut out = String::new();
    writeln!(
        out,
        "// Generated by crates/ynz-registry/build.rs — do not edit."
    )
    .unwrap();
    writeln!(out, "// Source: registry/features.toml").unwrap();
    writeln!(out).unwrap();

    emit_keywords(table, &mut out);
    emit_banned_declaration_keywords(table, &mut out);
    emit_banned_jargon(table, &mut out);
    emit_primitive_intrinsics(table, &mut out);
    emit_type_attached_constants(table, &mut out);
    emit_deferred_language_features(table, &mut out);
    emit_deferred_tooling_features(table, &mut out);
    emit_diagnostic_templates(table, &mut out);
    emit_muted_hint_domains(table, &mut out);
    emit_lint_rules(table, &mut out);

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    std::fs::write(out_dir.join("registry.rs"), &out)
        .unwrap_or_else(|e| panic!("failed to write OUT_DIR/registry.rs: {e}"));
}

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

type TomlTable = toml::map::Map<String, toml::Value>;

fn get_str<'a>(entry: &'a TomlTable, key: &str, kind: &str, entry_name: &str) -> &'a str {
    entry
        .get(key)
        .unwrap_or_else(|| {
            panic!("registry/features.toml: [[{kind}]] entry '{entry_name}': missing required field '{key}'")
        })
        .as_str()
        .unwrap_or_else(|| {
            panic!("registry/features.toml: [[{kind}]] entry '{entry_name}': field '{key}' must be a string")
        })
}

fn get_bool(entry: &TomlTable, key: &str, kind: &str, entry_name: &str, default: bool) -> bool {
    match entry.get(key) {
        None => default,
        Some(v) => v.as_bool().unwrap_or_else(|| {
            panic!("registry/features.toml: [[{kind}]] entry '{entry_name}': field '{key}' must be a boolean")
        }),
    }
}

fn get_str_array<'a>(
    entry: &'a TomlTable,
    key: &str,
    kind: &str,
    entry_name: &str,
) -> Vec<&'a str> {
    match entry.get(key) {
        None => vec![],
        Some(v) => {
            let arr = v.as_array().unwrap_or_else(|| {
                panic!("registry/features.toml: [[{kind}]] entry '{entry_name}': field '{key}' must be an array")
            });
            arr.iter()
                .map(|item| {
                    item.as_str().unwrap_or_else(|| {
                        panic!("registry/features.toml: [[{kind}]] entry '{entry_name}': field '{key}' must be an array of strings")
                    })
                })
                .collect()
        }
    }
}

fn get_entries<'a>(table: &'a TomlTable, kind: &str) -> Vec<&'a TomlTable> {
    match table.get(kind) {
        None => vec![],
        Some(v) => {
            let arr = v.as_array().unwrap_or_else(|| {
                panic!("registry/features.toml: '{kind}' must be an array of tables")
            });
            arr.iter()
                .map(|item| {
                    item.as_table().unwrap_or_else(|| {
                        panic!("registry/features.toml: each [[{kind}]] entry must be a table")
                    })
                })
                .collect()
        }
    }
}

fn check_no_duplicates(names: &[&str], kind: &str) {
    let mut seen = HashSet::new();
    for name in names {
        if !seen.insert(*name) {
            panic!(
                "registry/features.toml: [[{kind}]] has duplicate entry name '{name}' — \
                 each name must be unique within its kind"
            );
        }
    }
}

fn escape_str_array(items: &[&str]) -> String {
    let mut s = String::from("&[");
    for (i, item) in items.iter().enumerate() {
        if i > 0 {
            s.push_str(", ");
        }
        s.push_str(&format!("{item:?}"));
    }
    s.push(']');
    s
}

