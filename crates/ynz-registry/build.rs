        let hover_what_instead = entry.get("hover_what_instead").and_then(|v| v.as_str());
        let hover_why = entry.get("hover_why").and_then(|v| v.as_str());
        let hw = match hover_what {
            Some(s) => format!("Some({s:?})"),
            None => "None".to_string(),
        };
        let hwi = match hover_what_instead {
            Some(s) => format!("Some({s:?})"),
            None => "None".to_string(),
        };
