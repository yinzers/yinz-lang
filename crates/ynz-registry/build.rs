fn emit_primitive_intrinsics(table: &TomlTable, out: &mut String) {
    let kind = "primitive_intrinsic";
    let entries = get_entries(table, kind);
    // Overloads with the same name are intentional (e.g. range/1 and range/2) — skip duplicate check.

    writeln!(
        out,
        "pub static PRIMITIVE_INTRINSICS: &[crate::PrimitiveIntrinsicEntry] = &["
    )
    .unwrap();
    for entry in &entries {
        let name = get_str(entry, "name", kind, "<unknown>");
        let intr_kind = get_str(entry, "kind", kind, name);
        let receiver_type = entry.get("receiver_type").and_then(|v| v.as_str());
        let param_types = get_str_array(entry, "param_types", kind, name);
        // return_type is optional for print_type entries (they have no return value).
        let return_type = entry
            .get("return_type")
            .and_then(|v| v.as_str())
            .unwrap_or("");
        let since = get_str(entry, "since", kind, name);
        let doc = entry.get("doc").and_then(|v| v.as_str());

        let receiver_expr = match receiver_type {
            Some(rt) => format!("Some({rt:?})"),
            None => "None".to_string(),
        };
        let params_expr = escape_str_array(&param_types);
        let doc_expr = match doc {
            Some(d) => format!("Some({d:?})"),
            None => "None".to_string(),
        };

        writeln!(
            out,
            "    crate::PrimitiveIntrinsicEntry {{ name: {name:?}, kind: {intr_kind:?}, receiver_type: {receiver_expr}, param_types: {params_expr}, return_type: {return_type:?}, since: {since:?}, doc: {doc_expr} }},",
        )
        .unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(out).unwrap();
}

fn emit_type_attached_constants(table: &TomlTable, out: &mut String) {
    let kind = "type_attached_constant";
    let entries = get_entries(table, kind);
    // Uniqueness is (type_name, const_name) composite — same const_name on different types is valid.
    let mut seen = std::collections::HashSet::new();
    for e in &entries {
        let tn = get_str(e, "type_name", kind, "<unknown>");
        let cn = get_str(e, "const_name", kind, tn);
        let key = format!("{tn}.{cn}");
        if !seen.insert(key.clone()) {
            panic!("registry/features.toml: [[{kind}]] has duplicate entry '{key}' — (type_name, const_name) must be unique");
        }
    }

    writeln!(
        out,
        "pub static TYPE_ATTACHED_CONSTANTS: &[crate::TypeAttachedConstantEntry] = &["
    )
    .unwrap();
    for entry in &entries {
        let type_name = get_str(entry, "type_name", kind, "<unknown>");
        let const_name = get_str(entry, "const_name", kind, type_name);
        let value_type = get_str(entry, "value_type", kind, type_name);
        let value_literal = get_str(entry, "value_literal", kind, type_name);
        let since = get_str(entry, "since", kind, type_name);
        writeln!(
            out,
            "    crate::TypeAttachedConstantEntry {{ type_name: {type_name:?}, const_name: {const_name:?}, value_type: {value_type:?}, value_literal: {value_literal:?}, since: {since:?} }},",
        )
        .unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(out).unwrap();
}

